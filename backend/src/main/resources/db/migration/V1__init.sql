-- 처음 구조: 2026-10-20까지 Hibernate(ddl-auto=update)가 만들어 온 실제 DB 구조를 그대로 옮겼다 (pg_dump --schema-only).
-- 이미 있는 DB는 이 파일을 실행하지 않고 '1번까지 끝남'으로 장부에만 적는다 (spring.flyway.baseline-on-migrate).
-- 새 DB(테스트용 일회용 DB 등)는 이 파일로 표를 만든다.
-- 제약 이름(fk…, uk…)은 Hibernate가 지은 이름 그대로 둔다. 기존 DB와 새 DB의 이름이 같아야 나중 변경 파일이 양쪽에서 똑같이 돈다.
-- 작업 상태 검사의 CANCELLED는 10-05에 손으로 고친 것(db/manual/2026-10-05_job_status_cancelled.sql)을 반영한 상태다.

-- 논문 처리 작업
CREATE TABLE paper_job (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6) without time zone,
    file_name      varchar(255),
    status         varchar(255),
    updated_at     timestamp(6) without time zone,
    error_message  varchar(1000),
    result_json    text,
    title          varchar(1000),
    stage          varchar(20),
    progress_done  integer DEFAULT 0 NOT NULL,
    progress_total integer DEFAULT 0 NOT NULL,
    version        bigint DEFAULT 0 NOT NULL,
    CONSTRAINT paper_job_stage_check CHECK (stage IN ('EXTRACTING', 'PLANNING', 'WRITING', 'DONE')),
    CONSTRAINT paper_job_status_check CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'CANCELLED'))
);

-- 논문 문장 (번호가 근거를 가리키는 기준)
CREATE TABLE paper_sentence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number        integer NOT NULL,
    page          integer,
    section_title varchar(500),
    text          text NOT NULL,
    job_id        bigint NOT NULL,
    CONSTRAINT ukam8lj4pveh85cvydgi2luwi8n UNIQUE (job_id, number),
    CONSTRAINT fkas7panx38rfsd6v9ov3uvatci FOREIGN KEY (job_id) REFERENCES paper_job (id)
);

-- 만화 → 쪽 → 컷 → 대사·근거
CREATE TABLE comic (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    ending     text,
    setting    text,
    title      varchar(500),
    job_id     bigint NOT NULL,
    CONSTRAINT ukamf5bus47d18xx1fm79r84exl UNIQUE (job_id),
    CONSTRAINT fk9mssc7oa76nrsmwxioco387at FOREIGN KEY (job_id) REFERENCES paper_job (id)
);

CREATE TABLE comic_page (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beat        text,
    page_number integer NOT NULL,
    role        varchar(10),
    comic_id    bigint NOT NULL,
    CONSTRAINT fkgkx7e9wtk7dcowq8fvjxte6ob FOREIGN KEY (comic_id) REFERENCES comic (id)
);

CREATE TABLE comic_panel (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fact        text,
    panel_order integer NOT NULL,
    scene       text,
    staging     boolean NOT NULL,
    page_id     bigint NOT NULL,
    CONSTRAINT fkn2jler3m1yls1h53dxpu08hwq FOREIGN KEY (page_id) REFERENCES comic_page (id)
);

CREATE TABLE panel_line (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_order integer NOT NULL,
    speaker    varchar(20),
    text       text NOT NULL,
    panel_id   bigint NOT NULL,
    CONSTRAINT panel_line_speaker_check CHECK (speaker IN ('NURI', 'DOCTOR', 'NARRATION')),
    CONSTRAINT fkfx0uqupcnnknw4yckkhv25vmg FOREIGN KEY (panel_id) REFERENCES comic_panel (id)
);

CREATE TABLE panel_evidence (
    panel_id    bigint NOT NULL,
    sentence_id bigint NOT NULL,
    CONSTRAINT fkkgqylc0q4q90pii3dexprn0pu FOREIGN KEY (panel_id) REFERENCES comic_panel (id),
    CONSTRAINT fkrerb0jmdddoj1arvm4sl8pll0 FOREIGN KEY (sentence_id) REFERENCES paper_sentence (id)
);
